"""Convert Microsoft's pubs sample (pubs/instpubs.sql, T-SQL) into pubs_postgres.sql.

The schema, trigger, view and procedures are translated by hand (SCHEMA and OBJECTS
below). The INSERT data is read from the original file and rewritten for PostgreSQL:

  insert t values(...)   ->  INSERT INTO t (columns) VALUES (...), (...);
  $20.00                 ->  20.00
  0x4749...              ->  decode('4749...', 'hex')
  '06/12/94' (mdy)       ->  '1994-06-12'
  BIT 1/0/3              ->  true/false (SQL Server stores any non-zero BIT as 1)

Usage: python scripts/convert_pubs.py
"""
import re
from pathlib import Path

LAB_DIR = Path(__file__).resolve().parent.parent
SOURCE = LAB_DIR / "pubs" / "instpubs.sql"
TARGET = LAB_DIR / "pubs_postgres.sql"

# Column order of every table, as in the original CREATE TABLE statements.
COLUMNS = {
    "authors": ["au_id", "au_lname", "au_fname", "phone", "address", "city", "state", "zip", "contract"],
    "publishers": ["pub_id", "pub_name", "city", "state", "country"],
    "pub_info": ["pub_id", "logo", "pr_info"],
    "titles": ["title_id", "title", "type", "pub_id", "price", "advance", "royalty", "ytd_sales", "notes", "pubdate"],
    "titleauthor": ["au_id", "title_id", "au_ord", "royaltyper"],
    "stores": ["stor_id", "stor_name", "stor_address", "city", "state", "zip"],
    "sales": ["stor_id", "ord_num", "ord_date", "qty", "payterms", "title_id"],
    "roysched": ["title_id", "lorange", "hirange", "royalty"],
    "discounts": ["discounttype", "stor_id", "lowqty", "highqty", "discount"],
    # job_id is IDENTITY, the original inserts leave it out
    "jobs": ["job_desc", "min_lvl", "max_lvl"],
    "employee": ["emp_id", "fname", "minit", "lname", "job_id", "job_lvl", "pub_id", "hire_date"],
}
DATE_COLUMNS = {("titles", "pubdate"), ("sales", "ord_date"), ("employee", "hire_date")}
BOOL_COLUMNS = {("authors", "contract")}

HEADER = """\
-- =====================================================================
-- Pubs database: PostgreSQL 16 version
-- Source script: Microsoft sql-server-samples, northwind-pubs/instpubs.sql (MS SQL Server)
-- https://github.com/microsoft/sql-server-samples/blob/master/samples/databases/northwind-pubs/instpubs.sql
--
-- Tables, trigger, view and procedures were translated from T-SQL to PostgreSQL by hand.
-- The INSERT data was converted by scripts/convert_pubs.py, which reads pubs/instpubs.sql,
-- so the values are the same as in the original file.
--
-- How to run:
--   scripts\\db.cmd init-pubs   -- creates an empty pubs database and runs this file,
--   or connect to an existing pubs database and run this whole file.
--
-- Main conversions:
--   CREATE DATABASE / USE pubs           -> CREATE DATABASE pubs (scripts\\db.cmd init-pubs)
--   sp_addtype                           -> CREATE DOMAIN
--   BIT                                  -> BOOLEAN
--   TINYINT                              -> SMALLINT
--   MONEY                                -> NUMERIC(19,4)
--   DATETIME                             -> TIMESTAMP
--   IMAGE, 0x... literals                -> BYTEA, decode('...', 'hex')
--   IDENTITY(1,1)                        -> GENERATED BY DEFAULT AS IDENTITY
--   GETDATE()                            -> CURRENT_TIMESTAMP
--   LIKE '[0-9][0-9]...'                 -> ~ '^[0-9]{2}...$' (regular expression)
--   CLUSTERED / NONCLUSTERED index       -> plain B-tree index
--   T-SQL trigger on the inserted table  -> PL/pgSQL BEFORE ... FOR EACH ROW trigger
--   GROUP BY ... WITH ROLLUP             -> GROUP BY ROLLUP (...)
--   Procedure that returns a SELECT      -> PROCEDURE with an INOUT refcursor parameter
--   $20.00, '06/12/94' (mdy)             -> 20.00, '1994-06-12'
--   GO, raiserror, SET NOCOUNT, CHECKPOINT -> removed
--   UPDATE STATISTICS                    -> ANALYZE
-- =====================================================================

"""

SCHEMA = """\
-- ---------------------------------------------------------------------
-- 0. Drop existing objects so the script can be run again
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS titleview;
DROP TABLE IF EXISTS employee, pub_info, jobs, discounts, roysched, sales,
                     stores, titleauthor, titles, publishers, authors CASCADE;
DROP FUNCTION IF EXISTS employee_insupd() CASCADE;
DROP PROCEDURE IF EXISTS byroyalty, reptq1, reptq2, reptq3;
DROP DOMAIN IF EXISTS public.id, public.tid, public.empid;

-- ---------------------------------------------------------------------
-- 1. User-defined types (sp_addtype -> CREATE DOMAIN)
--    Created as in the original script, but the tables use the base types.
--    pg_catalog already has a system type called tid (a row's physical address),
--    so all three are created with the public schema in their name.
-- ---------------------------------------------------------------------
CREATE DOMAIN public.id    AS VARCHAR(11) NOT NULL;
CREATE DOMAIN public.tid   AS VARCHAR(6)  NOT NULL;
CREATE DOMAIN public.empid AS CHAR(9)     NOT NULL;

-- ---------------------------------------------------------------------
-- 2. Tables
-- ---------------------------------------------------------------------

-- Authors. au_id must look like 999-99-9999.
CREATE TABLE authors (
    au_id          CHAR(11)    CONSTRAINT UPKCL_auidind PRIMARY KEY
                               CHECK (au_id ~ '^[0-9]{3}-[0-9]{2}-[0-9]{4}$'),
    au_lname       VARCHAR(40) NOT NULL,
    au_fname       VARCHAR(20) NOT NULL,
    phone          CHAR(12)    NOT NULL DEFAULT 'UNKNOWN',
    address        VARCHAR(40),
    city           VARCHAR(20),
    state          CHAR(2),
    zip            CHAR(5)     CHECK (zip ~ '^[0-9]{5}$'),
    contract       BOOLEAN     NOT NULL
);

-- Publishers
CREATE TABLE publishers (
    pub_id         CHAR(4)     NOT NULL CONSTRAINT UPKCL_pubind PRIMARY KEY
                               CHECK (pub_id IN ('1389', '0736', '0877', '1622', '1756')
                                      OR pub_id ~ '^99[0-9]{2}$'),
    pub_name       VARCHAR(40),
    city           VARCHAR(20),
    state          CHAR(2),
    country        VARCHAR(30) DEFAULT 'USA'
);

-- Titles. MONEY -> NUMERIC(19,4), DATETIME -> TIMESTAMP
CREATE TABLE titles (
    title_id       CHAR(6)       CONSTRAINT UPKCL_titleidind PRIMARY KEY,
    title          VARCHAR(80)   NOT NULL,
    type           CHAR(12)      NOT NULL DEFAULT 'UNDECIDED',
    pub_id         CHAR(4)       REFERENCES publishers (pub_id),
    price          NUMERIC(19,4),
    advance        NUMERIC(19,4),
    royalty        INT,
    ytd_sales      INT,
    notes          VARCHAR(200),
    pubdate        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Links titles and authors (many-to-many)
CREATE TABLE titleauthor (
    au_id          CHAR(11)  REFERENCES authors (au_id),
    title_id       CHAR(6)   REFERENCES titles (title_id),
    au_ord         SMALLINT,
    royaltyper     INT,
    CONSTRAINT UPKCL_taind PRIMARY KEY (au_id, title_id)
);

-- Stores
CREATE TABLE stores (
    stor_id        CHAR(4)     NOT NULL CONSTRAINT UPK_storeid PRIMARY KEY,
    stor_name      VARCHAR(40),
    stor_address   VARCHAR(40),
    city           VARCHAR(20),
    state          CHAR(2),
    zip            CHAR(5)
);

-- Sales: one row per unique (store, order number, title)
CREATE TABLE sales (
    stor_id        CHAR(4)     NOT NULL REFERENCES stores (stor_id),
    ord_num        VARCHAR(20) NOT NULL,
    ord_date       TIMESTAMP   NOT NULL,
    qty            SMALLINT    NOT NULL,
    payterms       VARCHAR(12) NOT NULL,
    title_id       CHAR(6)     REFERENCES titles (title_id),
    CONSTRAINT UPKCL_sales PRIMARY KEY (stor_id, ord_num, title_id)
);

-- Royalty schedule by sales range
CREATE TABLE roysched (
    title_id       CHAR(6)   REFERENCES titles (title_id),
    lorange        INT,
    hirange        INT,
    royalty        INT
);

-- Discounts. DECIMAL(4,2) -> NUMERIC(4,2)
CREATE TABLE discounts (
    discounttype   VARCHAR(40)  NOT NULL,
    stor_id        CHAR(4)      REFERENCES stores (stor_id),
    lowqty         SMALLINT,
    highqty        SMALLINT,
    discount       NUMERIC(4,2) NOT NULL
);

-- Jobs. IDENTITY(1,1) -> GENERATED BY DEFAULT AS IDENTITY, TINYINT -> SMALLINT
CREATE TABLE jobs (
    job_id         SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_desc       VARCHAR(50) NOT NULL DEFAULT 'New Position - title not formalized yet',
    min_lvl        SMALLINT    NOT NULL CHECK (min_lvl >= 10),
    max_lvl        SMALLINT    NOT NULL CHECK (max_lvl <= 250)
);

-- Publisher logos and descriptions. IMAGE -> BYTEA
CREATE TABLE pub_info (
    pub_id         CHAR(4)  NOT NULL REFERENCES publishers (pub_id)
                            CONSTRAINT UPKCL_pubinfo PRIMARY KEY,
    logo           BYTEA,
    pr_info        TEXT
);

-- Employees. emp_id is CHAR(10), so trailing spaces are removed with rtrim() before the check.
CREATE TABLE employee (
    emp_id         CHAR(10)    CONSTRAINT PK_emp_id PRIMARY KEY
                               CHECK (rtrim(emp_id) ~ '^[A-Z]{3}[1-9][0-9]{4}[FM]$'
                                      OR rtrim(emp_id) ~ '^[A-Z]-[A-Z][1-9][0-9]{4}[FM]$'),
    fname          VARCHAR(20) NOT NULL,
    minit          CHAR(1),
    lname          VARCHAR(30) NOT NULL,
    job_id         SMALLINT    NOT NULL DEFAULT 1 REFERENCES jobs (job_id),
    job_lvl        SMALLINT    DEFAULT 10,
    pub_id         CHAR(4)     NOT NULL DEFAULT '9952' REFERENCES publishers (pub_id),
    hire_date      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- 3. Trigger: checks that an employee's level (job_lvl) is within the job's range.
--    T-SQL inserted table + ROLLBACK -> NEW row + RAISE EXCEPTION
-- ---------------------------------------------------------------------
CREATE FUNCTION employee_insupd()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_min_lvl SMALLINT;
    v_max_lvl SMALLINT;
BEGIN
    -- Read the job's level range from jobs
    SELECT min_lvl, max_lvl
    INTO v_min_lvl, v_max_lvl
    FROM jobs
    WHERE job_id = NEW.job_id;

    IF NEW.job_id = 1 AND NEW.job_lvl <> 10 THEN
        RAISE EXCEPTION 'Job id 1 expects the default level of 10.';
    ELSIF NOT (NEW.job_lvl BETWEEN v_min_lvl AND v_max_lvl) THEN
        RAISE EXCEPTION 'The level for job_id:% should be between % and %.',
            NEW.job_id, v_min_lvl, v_max_lvl;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER employee_insupd
BEFORE INSERT OR UPDATE ON employee
FOR EACH ROW EXECUTE FUNCTION employee_insupd();

-- ---------------------------------------------------------------------
-- 4. Data (converted from the INSERTs of the original file)
-- ---------------------------------------------------------------------
"""

OBJECTS = """\
-- ---------------------------------------------------------------------
-- 5. Indexes. PostgreSQL has no persistent CLUSTERED index, so these are plain B-tree indexes.
--    MS SQL only needs index names to be unique per table, but PostgreSQL needs them
--    unique per schema, so the three titleidind indexes get different names.
-- ---------------------------------------------------------------------
CREATE INDEX employee_ind           ON employee (lname, fname, minit);
CREATE INDEX aunmind                ON authors (au_lname, au_fname);
CREATE INDEX sales_titleidind       ON sales (title_id);
CREATE INDEX titleind               ON titles (title);
CREATE INDEX auidind                ON titleauthor (au_id);
CREATE INDEX titleauthor_titleidind ON titleauthor (title_id);
CREATE INDEX roysched_titleidind    ON roysched (title_id);

-- ---------------------------------------------------------------------
-- 6. View: titles with their authors, price and sales
-- ---------------------------------------------------------------------
CREATE VIEW titleview AS
SELECT title, au_ord, au_lname, price, ytd_sales, pub_id
FROM authors, titles, titleauthor
WHERE authors.au_id = titleauthor.au_id
  AND titles.title_id = titleauthor.title_id;

-- ---------------------------------------------------------------------
-- 7. Procedures of the original script.
--    A PostgreSQL PROCEDURE cannot return rows directly, so the result is
--    returned through an INOUT refcursor. Example call:
--      BEGIN; CALL reptq1(); FETCH ALL FROM reptq1; COMMIT;
-- ---------------------------------------------------------------------

-- au_id of the authors whose royaltyper equals the given percentage
CREATE PROCEDURE byroyalty(p_percentage INT, INOUT p_result refcursor DEFAULT 'byroyalty')
LANGUAGE plpgsql
AS $$
BEGIN
    OPEN p_result FOR
        SELECT au_id
        FROM titleauthor
        WHERE titleauthor.royaltyper = p_percentage;
END;
$$;

-- Average title price per publisher plus the overall average (ROLLUP)
CREATE PROCEDURE reptq1(INOUT p_result refcursor DEFAULT 'reptq1')
LANGUAGE plpgsql
AS $$
BEGIN
    OPEN p_result FOR
        SELECT CASE WHEN GROUPING(pub_id) = 1 THEN 'ALL' ELSE pub_id END AS pub_id,
               AVG(price)::NUMERIC(19,4) AS avg_price
        FROM titles
        WHERE price IS NOT NULL
        GROUP BY ROLLUP (pub_id)
        ORDER BY pub_id;
END;
$$;

-- Average ytd_sales per publisher and type.
-- AVG of integers returns an integer in MS SQL, hence TRUNC.
CREATE PROCEDURE reptq2(INOUT p_result refcursor DEFAULT 'reptq2')
LANGUAGE plpgsql
AS $$
BEGIN
    OPEN p_result FOR
        SELECT CASE WHEN GROUPING(type) = 1 THEN 'ALL' ELSE type END AS type,
               CASE WHEN GROUPING(pub_id) = 1 THEN 'ALL' ELSE pub_id END AS pub_id,
               TRUNC(AVG(ytd_sales))::INT AS avg_ytd_sales
        FROM titles
        WHERE pub_id IS NOT NULL
        GROUP BY ROLLUP (pub_id, type);
END;
$$;

-- Number of titles in a price range and type (the original AND/OR precedence is kept)
CREATE PROCEDURE reptq3(p_lolimit NUMERIC, p_hilimit NUMERIC, p_type CHAR(12),
                        INOUT p_result refcursor DEFAULT 'reptq3')
LANGUAGE plpgsql
AS $$
BEGIN
    OPEN p_result FOR
        SELECT CASE WHEN GROUPING(pub_id) = 1 THEN 'ALL' ELSE pub_id END AS pub_id,
               CASE WHEN GROUPING(type) = 1 THEN 'ALL' ELSE type END AS type,
               COUNT(title_id) AS cnt
        FROM titles
        WHERE price > p_lolimit AND price < p_hilimit AND type = p_type OR type LIKE '%cook%'
        GROUP BY ROLLUP (pub_id, type);
END;
$$;

-- ---------------------------------------------------------------------
-- 8. Update statistics (UPDATE STATISTICS -> ANALYZE)
-- ---------------------------------------------------------------------
ANALYZE publishers, employee, jobs, pub_info, titles, authors,
        titleauthor, sales, roysched, stores, discounts;
"""

TOKEN = re.compile(
    r"\s*(?:(?P<str>'(?:[^']|'')*')|(?P<hex>0x[0-9A-Fa-f]+)|(?P<money>\$[0-9.]+)"
    r"|(?P<num>-?[0-9]+(?:\.[0-9]+)?)|(?P<null>NULL))\s*(?:,|(?=\)))",
    re.S,
)
INSERT = re.compile(r"^insert\s+(\w+)\s*(?:\(([^)]*)\))?\s*values\s*\(", re.I | re.M)


def parse_values(text, start):
    """Parse a T-SQL VALUES list starting at `start`; return (tokens, end index)."""
    tokens, pos = [], start
    while True:
        m = TOKEN.match(text, pos)
        if not m:
            raise ValueError(f"cannot parse values near: {text[pos:pos + 60]!r}")
        kind = m.lastgroup
        tokens.append((kind, m.group(kind)))
        pos = m.end()
        if text[pos] == ")":
            return tokens, pos + 1


def mdy_to_iso(value):
    month, day, year = value.strip("'").split("/")
    year = int(year)
    year += 1900 if year >= 50 else 2000  # SQL Server two-digit year cutoff (2049)
    return f"'{year:04d}-{int(month):02d}-{int(day):02d}'"


def convert(table, column, kind, value):
    if kind == "null":
        return "NULL"
    if kind == "money":
        return value[1:]
    if kind == "hex":
        return f"decode('{value[2:]}', 'hex')"
    if (table, column) in DATE_COLUMNS:
        return mdy_to_iso(value)
    if (table, column) in BOOL_COLUMNS:
        return "false" if value == "0" else "true"
    if kind == "str":
        # The GitHub copy lost the u-umlaut of München (U+FFFD); restore it.
        return value.replace("�", "ü")
    return value


def read_inserts(text):
    """Yield (table, columns, values) for every INSERT in the original script."""
    for m in INSERT.finditer(text):
        table = m.group(1).lower()
        columns = [c.strip() for c in m.group(2).split(",")] if m.group(2) else COLUMNS[table]
        tokens, _ = parse_values(text, m.end())
        if len(tokens) != len(columns):
            raise ValueError(f"{table}: {len(tokens)} values for {len(columns)} columns")
        values = [convert(table, c, k, v) for c, (k, v) in zip(columns, tokens)]
        yield table, columns, values


def format_insert(table, columns, rows):
    head = f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n"
    body = ",\n".join("    (" + ", ".join(values) + ")" for values in rows)
    return head + body + ";\n"


def main():
    text = SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n")
    out = [HEADER, SCHEMA]

    # Group consecutive inserts that share a table and column list into one statement.
    groups = []
    for table, columns, values in read_inserts(text):
        if groups and groups[-1][0] == table and groups[-1][1] == columns:
            groups[-1][2].append(values)
        else:
            groups.append((table, columns, [values]))

    counts = {}
    for table, columns, rows in groups:
        if table not in counts:
            out.append(f"\n-- {table}\n")
        counts[table] = counts.get(table, 0) + len(rows)
        out.append(format_insert(table, columns, rows))

    out.append("\n" + OBJECTS)
    TARGET.write_text("".join(out), encoding="utf-8", newline="\n")
    summary = ", ".join(f"{t} {n}" for t, n in counts.items())
    print(f"wrote {TARGET.name}: {summary}")


if __name__ == "__main__":
    main()
