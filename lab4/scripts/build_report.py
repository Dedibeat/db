def build():
    doc = setup_document()
    cover(doc)
    contents(doc)
    environment(doc)

    for db in ("pubs", "northwind"):
        heading(doc, PARTS[db], 1, page_break=True)
        first = True
        for section in sections(db):
            if section.number == 0:
                conversion(doc, section)
                first = False
            else:
                task(doc, section, first)
                first = False

    doc.save(OUTPUT)
    all_ids = [d.id for db in ("pubs", "northwind") for s in sections(db) for d in s.demos]
    missing = [i for i in all_ids if not shot_files(i)]
    print(f"report {OUTPUT.name}: {len(all_ids) - len(missing)}/{len(all_ids)} screenshots present")
    if missing:
        print("missing screenshots: " + ", ".join(missing))

    # The same image in two slots is almost always a screenshot saved under the wrong name.
    seen = {}
    for demo_id in all_ids:
        for path in shot_files(demo_id):
            digest = hashlib.md5(path.read_bytes()).hexdigest()
            if digest in seen and seen[digest] != demo_id:
                print(f"WARNING: {path.name} is the same image as the one used for {seen[digest]}")
            seen.setdefault(digest, demo_id)


WORD_SCRIPT = r"""
$ErrorActionPreference = 'Stop'
$word = New-Object -ComObject Word.Application
$word.Visible = $false
$word.DisplayAlerts = 0
try {
    $doc = $word.Documents.Open('{docx}')
    foreach ($toc in $doc.TablesOfContents) { $toc.Update() }
    $doc.Fields.Update() | Out-Null
    foreach ($toc in $doc.TablesOfContents) { $toc.UpdatePageNumbers() }
    $doc.Save()
    if ('{pdf}') { $doc.ExportAsFixedFormat('{pdf}', 17) }
    $doc.Close()
} finally {
    $word.Quit()
}
"""


def refresh_with_word(pdf):
    script = WORD_SCRIPT.replace("{docx}", str(OUTPUT)).replace(
        "{pdf}", str(OUTPUT.with_suffix(".pdf")) if pdf else "")
    subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command", script], check=True)
    print("Word refreshed the table of contents" + (" and exported the PDF" if pdf else ""))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    build()
    if "--no-word" not in sys.argv:
        refresh_with_word("--pdf" in sys.argv)
