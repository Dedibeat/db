TOKEN_COLORS = [
    (Comment, ("3D6B35", False)),
    (String, ("8B3A1A", False)),
    (Keyword, (BLUE, True)),
    (Name.Builtin, (BLUE, False)),
]
LEXER = PostgresLexer()


def token_style(ttype):
    for parent, style in TOKEN_COLORS:
        if ttype in parent:
            return style
    return (DARK, False)


def code_lines(code):
    """Split highlighted tokens into lines of (text, color, bold) pieces."""
    lines, current = [], []
    for ttype, value in LEXER.get_tokens(code.expandtabs(4)):
        color, bold = token_style(ttype)
        parts = value.split("\n")
        for i, part in enumerate(parts):
            if i > 0:
                lines.append(current)
                current = []
            if part:
                current.append((part, color, bold))
    if current:
        lines.append(current)
    while lines and not lines[-1]:
        lines.pop()
    return lines


def code_block(doc, code, label=None, keep_next=False):
    """Highlighted SQL in a shaded box. keep_next holds a short block on one page with what follows."""
    table = full_width_table(doc)
    cell = table.cell(0, 0)
    cell_shading(cell, "F6F8FA")
    cell_borders(cell, left=("single", 18, "9DB4C8"))
    cell_margins(cell, top=70, left=150, bottom=70, right=100)
    first = True
    if label:
        p = cell.paragraphs[0]
        spacing(p, 0, 2)
        set_run_font(p.add_run(label), size=8.5, color=GRAY, bold=True)
        first = False
    for pieces in code_lines(code):
        p = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        spacing(p, 0, 0)
        p.paragraph_format.line_spacing = Pt(10.5)
        if not pieces:
            pieces = [(" ", DARK, False)]
        for text, color, bold in pieces:
            set_run_font(p.add_run(text), CODE_FONT, size=8.3, color=color, bold=bold)
    if keep_next:
        keep_table_with_next(table)
    gap(doc, keep_next=keep_next)


def shot_files(demo_id):
    if not SHOTS.is_dir():
        return []
    files = [p for p in SHOTS.iterdir()
             if p.suffix.lower() in (".png", ".jpg", ".jpeg")
             and (p.stem == demo_id or re.fullmatch(re.escape(demo_id) + r"_\d+", p.stem))]
    return sorted(files, key=lambda p: (len(p.stem), p.stem))


# Every screenshot is printed at the same scale, so the VS Code text has about the same
# size in all of them (13 px UI text -> about 8.5 pt, like the code listings). Wider images
# shrink to the text width, taller ones to MAX_SHOT_HEIGHT, and none is narrower than
# MIN_SHOT_WIDTH.
PT_PER_PX = 0.65
MIN_SHOT_WIDTH = Emu(int(TEXT_WIDTH * 0.4))
MAX_SHOT_HEIGHT = Inches(8.4)


def shot_width(path):
    with Image.open(path) as img:
        w, h = img.size
    width = max(Pt(w * PT_PER_PX), MIN_SHOT_WIDTH)
    width = min(width, TEXT_WIDTH, Emu(int(MAX_SHOT_HEIGHT * w / h)))
    return Emu(int(width))


def screenshot_slot(doc, demo_id, db, hint):
    """Real screenshots when present, otherwise a dashed placeholder naming the file."""
    files = shot_files(demo_id)
    if files:
        for path in files:
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            spacing(p, 4, 2, keep_next=True)
            p.add_run().add_picture(str(path), width=shot_width(path))
        return True

    table = full_width_table(doc)
    cell = table.cell(0, 0)
    cell_shading(cell, "FAFAFA")
    dashed = ("dashed", 8, "9AA4AE")
    cell_borders(cell, top=dashed, left=dashed, bottom=dashed, right=dashed)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    row = table.rows[0]
    row.height = Inches(1.5)
    lines = [
        ("Дэлгэцийн бүтэн зураг энд орно", 10, "6A737D", True),
        (f"screenshots/{demo_id}.png", 9.5, BLUE, False),
        (f"Дээрх скриптийг {db} өгөгдлийн сан дээр ажиллуулж авна. {hint}", 8.5, "6A737D", False),
    ]
    for i, (text, size, color, bold) in enumerate(lines):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        spacing(p, 0, 2)
        set_run_font(p.add_run(text), CODE_FONT if i == 1 else BODY_FONT, size=size, color=color, bold=bold)
    keep_table_with_next(table)
    return False


