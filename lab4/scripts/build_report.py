def set_run_font(run_or_style, name=BODY_FONT, size=None, bold=None, color=None, italic=None):
    font = run_or_style.font
    font.name = name
    if size is not None:
        font.size = Pt(size)
    if bold is not None:
        font.bold = bold
    if italic is not None:
        font.italic = italic
    if color is not None:
        font.color.rgb = RGBColor.from_string(color)
    rpr = run_or_style.element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.insert(0, fonts)
    for attr in list(fonts.attrib):
        if attr.endswith("Theme"):
            del fonts.attrib[attr]
    for key in ("ascii", "hAnsi", "eastAsia", "cs"):
        fonts.set(qn(f"w:{key}"), name)


def spacing(paragraph, before=0, after=4, line=None, keep_next=None):
    pf = paragraph.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    if line is not None:
        pf.line_spacing = line
    if keep_next is not None:
        pf.keep_with_next = keep_next


def cell_shading(cell, fill):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcpr.append(shd)


def cell_borders(cell, **edges):
    """edges: top/left/bottom/right = (val, size in 1/8 pt, color) or None for no border."""
    tcpr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        spec = edges.get(edge)
        if spec is None:
            el.set(qn("w:val"), "nil")
        else:
            val, size, color = spec
            el.set(qn("w:val"), val)
            el.set(qn("w:sz"), str(size))
            el.set(qn("w:space"), "0")
            el.set(qn("w:color"), color)
        borders.append(el)
    tcpr.append(borders)


def cell_margins(cell, top=0, left=0, bottom=0, right=0):
    tcpr = cell._tc.get_or_add_tcPr()
    mar = OxmlElement("w:tcMar")
    for edge, value in (("top", top), ("left", left), ("bottom", bottom), ("right", right)):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:w"), str(value))
        el.set(qn("w:type"), "dxa")
        mar.append(el)
    tcpr.append(mar)


def full_width_table(doc, rows=1, cols=1, widths=None):
    table = doc.add_table(rows=rows, cols=cols)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    tblpr = table._tbl.tblPr
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tblpr.append(layout)
    tblw = tblpr.find(qn("w:tblW"))
    tblw.set(qn("w:w"), str(int(TEXT_WIDTH / 635)))  # EMU -> twips
    tblw.set(qn("w:type"), "dxa")
    widths = widths or [TEXT_WIDTH]
    for row in table.rows:
        for cell, width in zip(row.cells, widths):
            cell.width = width
    return table


def gap(doc, size=3, keep_next=False):
    """Small empty paragraph. Also keeps consecutive tables from merging."""
    p = doc.add_paragraph()
    spacing(p, 0, 0, keep_next=keep_next)
    p.paragraph_format.line_spacing = Pt(size)
    return p


def keep_table_with_next(table):
    """Do not split the rows across pages and keep the table on the page of what follows."""
    for row in table.rows:
        trpr = row._tr.get_or_add_trPr()
        cant_split = OxmlElement("w:cantSplit")
        trpr.append(cant_split)
        for cell in row.cells:
            for p in cell.paragraphs:
                p.paragraph_format.keep_with_next = True


def add_field(paragraph, instruction, placeholder=""):
    """Complex field (begin / instr / separate / text / end), e.g. TOC, PAGE, NUMPAGES."""
    def fld_char(kind):
        run = paragraph.add_run()
        el = OxmlElement("w:fldChar")
        el.set(qn("w:fldCharType"), kind)
        run._r.append(el)
        return run

    fld_char("begin")
    run = paragraph.add_run()
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = f" {instruction} "
    run._r.append(instr)
    fld_char("separate")
    paragraph.add_run(placeholder)
    fld_char("end")


INLINE_CODE = re.compile(r"`([^`]+)`")


def rich_text(paragraph, text, size=11, color=DARK, bold=False):
    """Plain text with `inline code` spans set in Consolas."""
    pos = 0
    for m in INLINE_CODE.finditer(text):
        if m.start() > pos:
            set_run_font(paragraph.add_run(text[pos:m.start()]), size=size, color=color, bold=bold)
        set_run_font(paragraph.add_run(m.group(1)), CODE_FONT, size=size - 1.5, color=BLUE, bold=bold)
        pos = m.end()
    if pos < len(text):
        set_run_font(paragraph.add_run(text[pos:]), size=size, color=color, bold=bold)


